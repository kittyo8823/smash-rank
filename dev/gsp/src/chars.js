// 名前検索用（ひらがな・カタカナを同じ扱いに）
export function norm(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60))
    .replace(/[\s・.&/ー-]/g, '');
}
